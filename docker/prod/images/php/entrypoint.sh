#!/bin/sh
# Entrypoint for all PHP containers (fpm, queue, scheduler, cli).
set -e

APP_DIR=/var/www/app
RUNTIME_INI=/usr/local/etc/php/conf.d/zzz-runtime.ini

# --- Settings from the environment ------------------------------------------
# php.ini does not expand environment variables, so overrides are generated.
{
    echo "; Generated by entrypoint.sh, do not edit."
    [ -n "${PHP_MEMORY_LIMIT:-}" ] && echo "memory_limit = ${PHP_MEMORY_LIMIT}"
    [ -n "${PHP_OPCACHE_VALIDATE_TIMESTAMPS:-}" ] && \
        echo "opcache.validate_timestamps = ${PHP_OPCACHE_VALIDATE_TIMESTAMPS}"
    [ -n "${PHP_MAX_EXECUTION_TIME:-}" ] && echo "max_execution_time = ${PHP_MAX_EXECUTION_TIME}"
    # In CLI containers (queues, scheduler, artisan) opcache only gets in the way:
    # long-running processes keep stale bytecode after a deploy.
    case "$1" in
        php-fpm) ;;
        *) echo "opcache.enable_cli = 0" ;;
    esac
} > "${RUNTIME_INI}"

# --- Directories Laravel must be able to write to ---------------------------
# Code is mounted read-only; only storage, bootstrap/cache and vendor are rw.
mkdir -p \
    "${APP_DIR}/storage/app/public" \
    "${APP_DIR}/storage/framework/cache/data" \
    "${APP_DIR}/storage/framework/sessions" \
    "${APP_DIR}/storage/framework/views" \
    "${APP_DIR}/storage/logs" 2>/dev/null || true

# Permissions are checked AS www-data: under root the -w test always passes, and
# the problem would only surface halfway through composer install with the vague error
# "does not exist and could not be created". Typical cause: the directory did not
# exist on the host, so Docker created the mount point itself, as root.
if [ "$(id -u)" = "0" ]; then
    for dir in storage bootstrap/cache vendor; do
        if ! gosu www-data test -w "${APP_DIR}/${dir}" 2>/dev/null; then
            owner="$(stat -c '%u:%g' "${APP_DIR}/${dir}" 2>/dev/null || echo '?')"
            echo "[entrypoint] WARNING: ${APP_DIR}/${dir} is not writable:" \
                 "owner ${owner}, process runs as" \
                 "$(id -u www-data):$(id -g www-data). Fix: make fix-perms" >&2
        fi
    done
fi

# --- Start ------------------------------------------------------------------
# php-fpm and supervisord are master processes: they start as root and drop
# their workers to www-data themselves (see php-fpm.conf and supervisord.conf). They also
# need root to open the container's /dev/fd/1 for logs.
# Other CLI processes (scheduler, artisan) run as www-data.
case "$1" in
    php-fpm|supervisord|/usr/bin/supervisord)
        exec "$@"
        ;;
    *)
        if [ "$(id -u)" = "0" ]; then
            exec gosu www-data "$@"
        fi
        exec "$@"
        ;;
esac
